import { createReadStream, createWriteStream } from "node:fs";
import { mkdir, rename, stat, unlink } from "node:fs/promises";
import path from "node:path";
import type { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import { getEnv } from "@/server/env";

export interface ByteRange {
  /** First byte, inclusive. */
  start: number;
  /** Last byte, inclusive. */
  end: number;
}

/**
 * Where uploaded media bytes live. `LocalDiskMediaStorage` is the only implementation today;
 * an S3 implementation can be added without touching the services or routes.
 */
export interface MediaStorage {
  /** Streams `source` into `key` (never buffering the whole file) and returns the byte count. */
  save(key: string, source: Readable): Promise<number>;
  /** Size of the stored object, or undefined when it does not exist. */
  size(key: string): Promise<number | undefined>;
  /** Opens the object (or an inclusive byte range of it) for reading. */
  open(key: string, range?: ByteRange): Readable;
  /** Deletes the object. Missing objects are not an error. */
  remove(key: string): Promise<void>;
}

const SAFE_KEY = /^[A-Za-z0-9][A-Za-z0-9_.-]*$/;

/** Stores each object as a file in one flat directory. Keys are generated by the gateway. */
export class LocalDiskMediaStorage implements MediaStorage {
  private readonly directory: string;

  constructor(directory: string) {
    this.directory = path.resolve(directory);
  }

  private pathFor(key: string): string {
    if (!SAFE_KEY.test(key)) throw new Error("Invalid media storage key");
    return path.join(this.directory, key);
  }

  async save(key: string, source: Readable): Promise<number> {
    const target = this.pathFor(key);
    const partial = `${target}.part`;
    await mkdir(this.directory, { recursive: true });
    try {
      await pipeline(source, createWriteStream(partial));
      await rename(partial, target);
    } catch (error) {
      await unlink(partial).catch(() => undefined);
      throw error;
    }
    return (await stat(target)).size;
  }

  async size(key: string): Promise<number | undefined> {
    try {
      return (await stat(this.pathFor(key))).size;
    } catch {
      return undefined;
    }
  }

  open(key: string, range?: ByteRange): Readable {
    return createReadStream(this.pathFor(key), range);
  }

  async remove(key: string): Promise<void> {
    await unlink(this.pathFor(key)).catch((error: NodeJS.ErrnoException) => {
      if (error.code !== "ENOENT") throw error;
    });
  }
}

let cachedStorage: MediaStorage | undefined;

/** The configured storage (`MEDIA_STORAGE_DIR`), created lazily. */
export function getMediaStorage(): MediaStorage {
  cachedStorage ??= new LocalDiskMediaStorage(getEnv().MEDIA_STORAGE_DIR);
  return cachedStorage;
}

/** Tests point the gateway at a temporary directory. */
export function setMediaStorageForTests(storage: MediaStorage | undefined): void {
  cachedStorage = storage;
}
